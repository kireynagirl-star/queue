-- Run this entire file in Supabase Dashboard > SQL Editor > New query.
-- The table is accessed only through the Express server using the service-role key.
-- Never put SUPABASE_SERVICE_ROLE_KEY in browser code.

create table if not exists public.pickup_queues (
  id bigint generated by default as identity primary key,
  queue_date date not null default (now() at time zone 'Asia/Bangkok')::date,
  queue_number integer not null,
  queue_code text not null,
  customer_name text not null,
  order_number text not null default '',
  product_summary text not null,
  note text not null default '',
  status text not null default 'waiting'
    check (status in ('waiting', 'calling', 'done')),
  created_at timestamptz not null default now(),
  called_at timestamptz,
  completed_at timestamptz,
  unique (queue_date, queue_number),
  unique (queue_date, queue_code)
);

create index if not exists pickup_queues_date_status_idx
  on public.pickup_queues (queue_date, status, queue_number);

-- API access is handled by the server. Disable direct anonymous/authenticated access.
alter table public.pickup_queues enable row level security;
revoke all on table public.pickup_queues from anon, authenticated;
